#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const helper=fs.readFileSync(path.join(root,'src/booked-competition.js'),'utf8');
const booking=fs.readFileSync(path.join(root,'src/sponsor.js'),'utf8');
const rules=fs.readFileSync(path.join(root,'src/admin-scoring.js'),'utf8');
const events=fs.readFileSync(path.join(root,'src/events.js'),'utf8');
const ui=fs.readFileSync(path.join(root,'public/js/v7.js'),'utf8');
const publicUI=fs.readFileSync(path.join(root,'public/js/app.js'),'utf8');
for(const txt of [helper,booking,rules,events])new vm.Script(txt);
new vm.Script(ui.replace(/^import .*$/gm,'').replace(/\bexport\s+(?=(?:async\s+)?function\b)/g,''));
new vm.Script(publicUI.replace(/^import .*$/gm,''));
const m={exports:{}};
vm.runInNewContext(helper,{module:m},{timeout:2000});
const {validate,publicRule}=m.exports;
assert.equal(validate('best',['stack']).ok,true);
assert.equal(validate('best',['stack']).scoreRule,'best');
assert.equal(validate('best',['stack','gl-pop-defense']).ok,false);
assert.equal(validate('total',['stack']).ok,false);
assert.equal(validate('total',['stack','gl-pop-defense']).scoreRule,'sum_best');
assert.equal(validate('total',['stack','stack']).ok,false);
for(const bad of ['random','subscriber_goal','fastest','hybrid',''])assert.equal(validate(bad,['stack']).ok,false,'Unsupported skill format '+bad);
assert.match(publicRule({booking_id:1,score_rule:'best'}),/shortest server-measured run/);
assert.equal(publicRule({score_rule:'best'}),null,'Do not rewrite rules of unrelated historic giveaways');
assert.match(booking,/if\(!contestCheck\.ok\)return bad\(res,400,contestCheck\.error\)/);
assert.ok(booking.indexOf('if(!contestCheck.ok)')<booking.indexOf('const info = db.prepare(\x60INSERT INTO bookings'),'Invalid booking must not create an orphan row');
assert.match(booking,/UPDATE giveaways SET score_rule=\?/);
assert.doesNotMatch(booking,/comp === 'random' \? 'random'/);
assert.match(rules,/g\.booking_id && g\.score_rule === 'best'/);
assert.match(rules,/ORDER BY ws DESC, sdur ASC, \(sk IS NULL\) ASC, sk DESC, id ASC/);
assert.match(events,/winner_rule: require\('\.\/booked-competition'\)\.publicRule\(g\)/);
assert.match(publicUI,/How the winner is decided/);
assert.doesNotMatch(ui,/random: 'Random draw among qualifying players'/);
assert.match(ui,/shortest server-measured qualifying run/);
console.log(JSON.stringify({pass:true,scoreOnlyBooking:true,randomProposalsRejected:true,clearOneGameAndMultiGameModes:true,serverTimeTiebreak:true,exactTieSkillPlayoff:true,nativeDatabaseAndDeviceTested:false}));
