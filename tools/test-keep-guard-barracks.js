#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../public/games-lib');
let definition, keepConfig;
const K={run:def=>definition=def};
const browser={};
vm.runInNewContext(fs.readFileSync(path.join(root,'td.js'),'utf8'),{window:browser,Kit:K},{timeout:2000});
const engine=browser.TD;
browser.TD=config=>{keepConfig=config;};
vm.runInNewContext(fs.readFileSync(path.join(root,'keep-guard/game.js'),'utf8'),{window:browser,Kit:K},{timeout:2000});
assert.ok(keepConfig,'The real Keep Guard entrypoint must register its game configuration');
assert.equal(keepConfig.towers.filter(x=>x.kind==='barracks').length,1);
assert.match(keepConfig.help,/guards that stop ground raiders/i);
assert.equal(typeof keepConfig.drawGuard,'function');
engine(keepConfig);
assert.equal(typeof definition.update,'function');
const base=()=>({W:800,H:450,kd:()=>false,ptr:{pressed:false},RI:()=>1,sfx:()=>{},float:()=>{},burst:()=>{},shake:()=>{},flash:()=>{},add:()=>{},mark:()=>{},frames:1});
const enemy=(flight=false)=>({hp:1000,max:1000,sp:40,v:25,c:'#fff',r:9,d:2,x:100,y:110,slow:0,fly:flight});
let g=base();definition.init(g);
const slot=keepConfig.towers.findIndex(x=>x.kind==='barracks');
g.tw.push({k:slot,c:2,r:2,x:100,y:150,cd:0,lv:1,a:0});
g.en.push(enemy());g.wt=500;
definition.update(g,.25);
assert.equal(g.en[0].d,2,'Ground raider should be stopped by defender');
assert.ok(g.en[0].hp<1000,'Defender must inflict real gameplay damage');
assert.ok(g.tw[0].guardHP<12,'Guard must lose health during interception');
const d=base();definition.init(d);d.tw.push({k:slot,c:2,r:2,x:100,y:150,cd:0,lv:1,a:0});d.en.push(enemy(true));d.wt=500;
definition.update(d,.25);
assert.ok(d.en[0].d>2,'Flying enemy must not be intercepted by ground guard');
const weakened=base();definition.init(weakened);weakened.tw.push({k:slot,c:2,r:2,x:100,y:150,cd:0,lv:1,a:0,guardHP:.1,guardHitCd:0,guardRespawn:0});
weakened.en.push({...enemy(),sp:0,v:2000});weakened.wt=500;
definition.update(weakened,.25);
assert.equal(weakened.tw[0].guardHP,0,'Defender must be defeatable');
for(let i=0;i<13;i++)definition.update(weakened,.25);
assert.ok(weakened.tw[0].guardHP>0,'Defender must eventually respawn');
console.log(JSON.stringify({pass:true,groundBlocks:true,meleeDamage:true,defenderDamageAndRespawn:true,flyingEnemyNotBlocked:true,realPhoneQA:false}));
