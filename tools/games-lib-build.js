// Games Library builder: writes public/games-lib/<slug>/index.html + CREDITS.md for built games and catalog.json.
// Usage: node tools/games-lib-build.js
const fs = require('fs'); const path = require('path');
const { games, CATS, EXTERNAL } = require('../src/games-lib');
const ROOT = path.join(__dirname, '..', 'public', 'games-lib');
const esc = (s) => String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
let n = 0;
for (const g of games) {
  const dir = path.join(ROOT, g.slug); if (!fs.existsSync(path.join(dir, 'game.js')) && g.build === 'built') { console.log('missing', g.slug); continue; }
  if (g.build === 'built') {
    const uses = [...fs.readFileSync(path.join(dir, 'game.js'), 'utf8').matchAll(/@uses ([\w.-]+)/g)].map(m => `<script src="../${m[1]}"></script>`).join('');
    fs.writeFileSync(path.join(dir, 'index.html'), `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no,viewport-fit=cover">
<title>${esc(g.title)} - The Gaming Hub</title><meta name="theme-color" content="#050714"><link rel="stylesheet" href="../lib.css"></head>
<body class="glplay"><a class="glback" href="/games-lib/index.html" aria-label="Back to the library">&#8592;</a>
<script src="../adapter.js"></script><script src="../kit.js"></script>${uses}<script src="game.js"></script></body></html>\n`);
    fs.writeFileSync(path.join(dir, 'CREDITS.md'), `# ${g.title}\n\nOriginal game built for The Gaming Hub (Trap Tech Solutions). Code: MIT (see ../LICENSE-HUB.md). Art: vector shapes drawn in code. Sound: synthesized at runtime with WebAudio. No third-party assets.\n`);
  }
  n++;
}
fs.writeFileSync(path.join(ROOT, 'catalog.json'), JSON.stringify({ categories: CATS, games: games.map(({ ref_internal, ...g }) => g), external: EXTERNAL }));
console.log('built', n, 'of', games.length);

// ---------- docs/GAMES-LIB.md (progress table + research) ----------
const RES = JSON.parse(fs.readFileSync(path.join(__dirname, 'games-lib-research.json'), 'utf8'));
let E2E = {}; try { E2E = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'screenshots', 'v7', 'games-lib', 'e2e-results.json'), 'utf8')); } catch (e) {}
const sizeOf = (d) => { let n = 0; for (const f of fs.readdirSync(d, { withFileTypes: true })) n += f.isDirectory() ? sizeOf(path.join(d, f.name)) : fs.statSync(path.join(d, f.name)).size; return n; };
const rows = games.map((g, i) => { const e = E2E[g.slug]; const r = RES[g.slug] || {}; const kb = fs.existsSync(path.join(ROOT, g.slug)) ? Math.round(sizeOf(path.join(ROOT, g.slug)) / 1024) : 0;
  return `| ${i + 1} | ${g.title} | ${g.ref_internal} | ${g.category} | ${g.tier} | ${g.competition} | ${g.build} | ${g.licence.split(';')[0]} | ${g.giveaway ? 'yes' : 'no (just for fun)'} | ${g.ac.perSec}/s, L2 | ${kb} KB | ${e ? (e.pass ? 'PASS' : 'FAIL') + ` (fps ${e.desktop.fps}/${e.mobile.fps})` : 'not run'} |`; });
const byCat = CATS.map(c => `${c}: ${games.filter(g => g.category === c).length}`).join(' | ');
const research = games.filter(g => RES[g.slug]).map(g => `- **${g.title}** (ref: ${g.ref_internal}) - picked: ${RES[g.slug].picked}. Rejected: ${(RES[g.slug].rejected || []).join('; ')}.`).join('\n');
const doc = `# Games Library (The Gaming Hub)

Status file for the Games Library worker. **On restart, read this file and continue with the next batch listed under "Next".**
Generated by \`node tools/games-lib-build.js\` from \`src/games-lib.js\` (registry), \`tools/games-lib-research.json\` (sourcing notes) and
\`screenshots/v7/games-lib/e2e-results.json\` (last test run). Do not hand-edit the tables.

## Totals
- Playable library games: **${games.length}** (${games.filter(g => g.build === 'vendored').length} vendored open source, ${games.filter(g => g.build === 'built').length} original builds)
- Giveaway-eligible: ${games.filter(g => g.giveaway).length}; Just for fun: ${games.filter(g => !g.giveaway).length}
- By category: ${byCat}
- External "Just for fun" links (not hosted): ${EXTERNAL.length}

## How it fits together
- Files: \`public/games-lib/<slug>/\` (index.html, game.js, CREDITS.md, thumb.jpg, LICENSE for vendored code). Shared engine code: \`kit.js\` (canvas, input, touch stick/buttons, particles, WebAudio SFX, title/game-over), \`adapter.js\` (Hub run session), \`runner3d.js\`, \`td.js\`, \`arena.js\` (shared mechanics engines).
- Registry: \`src/games-lib.js\` (metadata card: category, tier, competition type, scoring, event length, giveaway_eligible, anti-cheat level L2, rate ceiling, source + licence). Served at \`GET /api/games-lib\`; library page \`/games-lib/index.html\`.
- Scoring: \`adapter.js\` calls \`POST /api/run/start\` (signed single-use token + seed) when a run begins, logs scoring events in the L3 event format of \`src/ac-levels.js\` plus input telemetry, and submits \`POST /api/score\` at game over. Server checks (L2): token signature/owner/TTL/single use, server-measured time vs the per-game rate ceiling (flag above perSec*t+grace, hard reject above 2x), telemetry, submit bursts.
- Shared-file hooks (all marked \`[games-lib hook]\`): \`src/config.js\` (GAME_MAP/gameInfo/giveawayEligible include library games; LIB_GAMES export), \`src/server.js\` (mount GET /api/games-lib), \`src/results.js\` (giveaway cap SQL includes library games), \`public/js/app.js\` (link to the library from /games).
- Tests: \`BASE=http://localhost:8795 node tools/e2e-games-lib.js [slugs]\` (desktop + iPhone 13, random input session, console errors, accepted legit score, rejected forged score, FPS, thumbnail capture).

## Progress table
| # | Hub name | Reference (internal) | Category | Tier | Competition | Build | Licence | Giveaway | Rate ceiling / AC | Size | Last e2e |
|---:|---|---|---|---|---|---|---|---|---|---:|---|
${rows.join('\n')}

## Sourcing research (picked vs rejected)
${RES._method}

${research}

## Next
${fs.existsSync(path.join(__dirname, 'games-lib-next.md')) ? fs.readFileSync(path.join(__dirname, 'games-lib-next.md'), 'utf8') : ''}
`;
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'GAMES-LIB.md'), doc);
console.log('docs/GAMES-LIB.md written');
